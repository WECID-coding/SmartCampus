/**
 * Find room location by ID or exact/fuzzy search
 */
function findCampusLocation(query) {
  if (!query) return null;
  const q = String(query).trim().toLowerCase();
  return CAMPUS_LOCATIONS.find(loc => loc.id.toLowerCase() === q || loc.name.toLowerCase() === q) || null;
}

/**
 * Filter rooms matching user search query
 */
function searchCampusLocations(query, limit = 12) {
  if (!query || !query.trim()) {
    return CAMPUS_LOCATIONS.slice(0, limit);
  }
  const q = query.trim().toLowerCase();
  const qTokens = q.split(/\s+/);

  const scored = [];
  for (const loc of CAMPUS_LOCATIONS) {
    let score = 0;
    const nameLower = loc.name.toLowerCase();
    const idLower = loc.id.toLowerCase();
    const keywords = loc.keywords;

    if (idLower === q || nameLower === q) {
      score += 100;
    } else if (nameLower.startsWith(q) || idLower.startsWith(q)) {
      score += 50;
    } else if (nameLower.includes(q)) {
      score += 30;
    } else if (keywords.includes(q)) {
      score += 20;
    }

    const allTokensMatch = qTokens.every(tok => keywords.includes(tok));
    if (allTokensMatch) {
      score += 15;
    }

    if (score > 0) {
      scored.push({ loc, score });
    }
  }

  scored.sort((a, b) => b.score - a.score || a.loc.name.localeCompare(b.loc.name));
  return scored.slice(0, limit).map(item => item.loc);
}

